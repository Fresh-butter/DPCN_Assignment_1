"""
crosscheck.py -- cross-network comparisons.

The three members each built a different network from one survey. Several of
the project's strongest results only exist when those networks are compared,
and a comparison belongs to no single member -- so it lives here, alongside
`common/`, as joint work.

**This module imports no member's code.** It reads their exported CSVs from
`member_*/tables/`, which are published outputs, not internals. That keeps the
no-cross-member-imports rule intact (each member's notebook still runs
standalone and is still graded on its own directory) while letting the
comparison be regenerated by a notebook rather than computed by hand.

Consequence worth knowing: this notebook must be run *after* all three member
notebooks, because it consumes what they produce.

The three quantities compared per statement:

    A  abs_gap          how sharply a statement separates A's two student
                        communities            (table09_community_profile.csv)
    B  leverage         how far a perturbation to a statement propagates
                        through the signed network (table06_leverage_ranking.csv)
    C  deviation_degree how many students answered it >1 SD from the class mean
                        (table03_item_degree.csv)

Nothing here is stochastic, so there is no seed to set: correlations and group
means are deterministic functions of the inputs.
"""

from pathlib import Path

import pandas as pd
from scipy.stats import pearsonr, spearmanr

REPO_ROOT = Path(__file__).resolve().parents[2]

MEMBER_DIRS = {
    "A": REPO_ROOT / "member_a_agreement_net",
    "B": REPO_ROOT / "member_b_statement_net",
    "C": REPO_ROOT / "member_c_bipartite_net",
}

BLOCK_ORDER = ["T", "E", "S", "V"]


def member_table(member: str, filename: str) -> pd.DataFrame:
    """Read one exported table from a member's `tables/` directory."""
    path = MEMBER_DIRS[member] / "tables" / filename
    if not path.exists():
        raise FileNotFoundError(
            f"{path} is missing. Run member {member}'s notebook before this one."
        )
    return pd.read_csv(path)


# ---------------------------------------------------------------------------
# Item-level comparison
# ---------------------------------------------------------------------------

def item_level_frame() -> pd.DataFrame:
    """
    One row per statement, carrying each member's measure of its importance.

    Inner-joined on the item code. B's leverage is defined only on the giant
    component, so T08 and T09 -- isolates in the signed network -- drop out and
    58 of the 60 statements remain for any comparison involving B.
    """
    a = member_table("A", "table09_community_profile.csv")[["item", "block", "abs_gap"]]
    b = member_table("B", "table06_leverage_ranking.csv")[["item", "leverage"]]
    c = member_table("C", "table03_item_degree.csv")[["node", "degree"]].rename(
        columns={"node": "item", "degree": "deviation_degree"}
    )
    return (a.merge(c, on="item", how="left")
             .merge(b, on="item", how="left")
             .sort_values("item")
             .reset_index(drop=True))


PAIRS = [
    ("abs_gap", "leverage",
     "A: separates the two student blocs", "B: dynamical leverage"),
    ("leverage", "deviation_degree",
     "B: dynamical leverage", "C: how many students deviate"),
    ("abs_gap", "deviation_degree",
     "A: separates the two student blocs", "C: how many students deviate"),
]


def item_level_correlations(df: pd.DataFrame) -> pd.DataFrame:
    """Pearson and Spearman for each pair of measures, on complete cases only."""
    rows = []
    for x, y, xlab, ylab in PAIRS:
        sub = df[[x, y]].dropna()
        r, p_r = pearsonr(sub[x], sub[y])
        rho, p_rho = spearmanr(sub[x], sub[y])
        rows.append({
            "measure_x": x, "measure_y": y,
            "description_x": xlab, "description_y": ylab,
            "n_items": len(sub),
            "pearson_r": r, "pearson_p": p_r,
            "spearman_rho": rho, "spearman_p": p_rho,
        })
    return pd.DataFrame(rows)


def block_profile(df: pd.DataFrame) -> pd.DataFrame:
    """Each member's measure averaged within a survey block, plus block ranks."""
    g = df.groupby("block").agg(
        n_items=("item", "size"),
        mean_abs_gap=("abs_gap", "mean"),
        mean_leverage=("leverage", "mean"),
        sd_leverage=("leverage", "std"),
        mean_deviation_degree=("deviation_degree", "mean"),
    ).reindex(BLOCK_ORDER)
    # rank 1 = highest on that measure
    g["rank_abs_gap"] = g["mean_abs_gap"].rank(ascending=False).astype(int)
    g["rank_leverage"] = g["mean_leverage"].rank(ascending=False).astype(int)
    g["rank_deviation"] = g["mean_deviation_degree"].rank(ascending=False).astype(int)
    return g.reset_index()


# ---------------------------------------------------------------------------
# Network-level comparison
# ---------------------------------------------------------------------------

def network_comparison() -> pd.DataFrame:
    """
    The three networks side by side, from each member's own exported tables.

    Nothing is recomputed here. Where a member did not export a quantity the
    cell is left empty rather than re-deriving it in this notebook, which would
    risk this file and that member's FINDINGS.md disagreeing.
    """
    a_edges = member_table("A", "table01_edge_rule_comparison.csv")
    a_thresh = a_edges[a_edges["rule"] == "threshold"].iloc[0]
    a_mod = member_table("A", "table11_modularity_null.csv").iloc[0]

    b_rule = member_table("B", "table00_edge_rule_sensitivity.csv").iloc[0]
    b_bal = member_table("B", "table05_balance_summary.csv").iloc[0]

    c_nodf = member_table("C", "table04_nodf.csv").iloc[0]
    c_mod = member_table("C", "table05_modularity_null.csv")
    c_stu = c_mod[c_mod["projection"] == "student_codissent"].iloc[0]

    rows = [
        {"network": "A — agreement (students)", "owner": "Vishal",
         "nodes": int(a_thresh["n_nodes"]), "edges": int(a_thresh["n_edges"]),
         "density": a_thresh["density"],
         "modularity_Q": a_mod["modularity_observed"],
         "Q_null_mean": a_mod["modularity_null_mean"],
         "Q_null_z": a_mod["z_score"]},
        {"network": "B — signed statements", "owner": "Harith",
         "nodes": int(b_rule["n_nodes"]), "edges": int(b_rule["n_edges"]),
         "density": b_rule["density"],
         "modularity_Q": pd.NA, "Q_null_mean": pd.NA, "Q_null_z": pd.NA},
        {"network": "C — bipartite deviation", "owner": "Navneet",
         "nodes": int(c_nodf["n_students"] + c_nodf["n_items"]),
         "edges": int(c_nodf["n_edges"]),
         "density": pd.NA,
         "modularity_Q": pd.NA, "Q_null_mean": pd.NA, "Q_null_z": pd.NA},
        {"network": "C — student co-dissent projection", "owner": "Navneet",
         "nodes": int(c_nodf["n_students"]), "edges": pd.NA, "density": pd.NA,
         "modularity_Q": c_stu["modularity_observed"],
         "Q_null_mean": c_stu["modularity_null_mean"],
         "Q_null_z": c_stu["z_score"]},
    ]
    return pd.DataFrame(rows)


if __name__ == "__main__":
    df = item_level_frame()
    print(f"item-level frame: {df.shape[0]} statements, "
          f"{df['leverage'].notna().sum()} with a leverage value")

    print("\nitem-level correlations:")
    print(item_level_correlations(df)[
        ["measure_x", "measure_y", "n_items", "pearson_r", "spearman_rho", "spearman_p"]
    ].to_string(index=False))

    print("\nblock profile:")
    print(block_profile(df).to_string(index=False))

    print("\nnetwork comparison:")
    print(network_comparison().to_string(index=False))
